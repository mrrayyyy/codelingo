import { test, expect } from "@playwright/test";

test("import → vocabulary context → FSRS review → reading → settings", async ({ page, request }) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/");
  await expect(page.getByRole("heading", { name: "A little progress, every day." })).toBeVisible();
  await page.getByRole("button", { name: "Import repository", exact: true }).first().click();
  const dialog = page.getByRole("dialog");
  await expect(dialog).toBeVisible();
  const importedResponse = page.waitForResponse(response => response.url().endsWith("/api/imports/sample") && response.status() === 202);
  await dialog.getByRole("button", { name: "Try the Atlas API sample repository" }).click();
  const imported = await (await importedResponse).json();
  await expect(dialog).not.toBeVisible();
  await page.getByRole("navigation").getByRole("button", { name: "My repositories" }).click();
  await expect(page.locator(".repository-row").first().getByText("Ready to learn")).toBeVisible({ timeout: 60_000 });
  const repoResponse = await request.get("/api/repos");
  const repos = await repoResponse.json();
  const sample = repos.find((r: { id: string }) => r.id === imported.repo_id);
  expect(sample.words).toBeGreaterThan(5);
  await page.getByRole("navigation").getByRole("button", { name: "Vocabulary", exact: true }).click();
  await page.getByPlaceholder("Search words, definitions, topics…").fill("retrieve");
  await page.getByRole("button", { name: /^retrieve verb/ }).first().click();
  await expect(page.getByRole("heading", { name: "The word in your project" })).toBeVisible();
  await expect(page.locator(".monaco-editor")).toBeVisible({ timeout: 20_000 });
  await expect(page.locator(".vocab-highlight").first()).toBeVisible();
  await page.getByRole("button", { name: "Review vocabulary", exact: true }).click();
  await page.getByRole("button", { name: "Reveal meaning" }).click();
  await expect(page.locator(".flashcard-answer")).toBeVisible();
  await page.getByRole("button", { name: /^Good Remembered/ }).click();
  await expect(page.getByText("1 reviewed this session")).toBeVisible();
  await page.getByRole("navigation").getByRole("button", { name: "Practice studio" }).click();
  await page.getByRole("button", { name: "Start practice" }).click();
  await expect(page.locator(".answer-options")).toBeVisible();
  await page.locator(".option").first().click();
  await page.getByRole("button", { name: "Check my answer" }).click();
  await expect(page.locator(".feedback")).toBeVisible();
  await page.getByRole("button", { name: "Settings & preferences" }).click();
  await page.getByLabel("Daily exercise goal", { exact: true }).fill("12");
  await page.getByRole("button", { name: "Save preferences" }).click();
  await expect(page.getByRole("status").filter({ hasText: "Your preferences have been saved." })).toBeVisible();
  await page.getByRole("button", { name: "Switch to Vietnamese" }).click();
  await expect(page.getByRole("heading", { name: "Cá nhân hóa không gian học." })).toBeVisible();
  await expect(page.locator("html")).toHaveAttribute("lang", "vi");
  await page.getByRole("button", { name: "Chuyển sang tiếng Anh" }).click();
  const download = await request.get("/api/export/anki");
  expect(download.status()).toBe(200);
  expect(download.headers()["content-disposition"]).toContain(".apkg");
  await request.delete(`/api/repos/${sample.id}`);
  expect(errors).toEqual([]);
});

test("responsive navigation, import validation, and keyboard dismissal", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/");
  await expect(page.getByRole("heading", { name: "A little progress, every day." })).toBeVisible();
  const overflows = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
  expect(overflows).toBe(false);
  await page.getByRole("button", { name: "Import repository", exact: true }).first().click();
  await page.getByRole("dialog").getByLabel("Public repository URL").fill("https://example.com/private");
  await page.getByRole("button", { name: "Find my learning material" }).click();
  await expect(page.getByRole("dialog").getByRole("alert")).toContainText("public repository URL");
  await page.keyboard.press("Escape");
  await expect(page.getByRole("dialog")).not.toBeVisible();
});
